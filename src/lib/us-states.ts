export function usStateToAbbreviation(value: string): string | null {
  const trimmed = value.trim();
  if (trimmed.length === 2) {
    const upper = trimmed.toUpperCase();
    if (Object.values(US_STATE_ABBREVIATIONS).includes(upper)) return upper;
  }
  if (isUsState(trimmed)) return US_STATE_ABBREVIATIONS[trimmed];
  const match = US_STATES.find(
    (state) => state.toLowerCase() === trimmed.toLowerCase(),
  );
  return match ? US_STATE_ABBREVIATIONS[match] : null;
}
